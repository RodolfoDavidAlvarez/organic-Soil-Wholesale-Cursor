import puppeteer from 'puppeteer';
import assert from 'node:assert/strict';
const browser = await puppeteer.launch({headless:true});
try {
 const page=await browser.newPage(); const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 await page.setViewport({width:390,height:844});
 await page.goto('http://127.0.0.1:5188/landscaper-supply',{waitUntil:'networkidle2'});
 await page.waitForSelector('.rls-card');
 assert.equal(await page.$$eval('.rls-card',x=>x.length),6);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.$$eval('.rls img', imgs => imgs.forEach(i => i.loading = 'eager'));
 await page.waitForFunction(()=>[...document.querySelectorAll('.rls img')].every(i=>i.complete && i.naturalWidth > 0));
 await page.screenshot({path:'artifacts/rls/mobile.png',fullPage:true});
 await page.setViewport({width:1440,height:1000}); await page.screenshot({path:'artifacts/rls/desktop.png',fullPage:true});
 const clickText=async(text)=>page.evaluate(text=>{const el=[...document.querySelectorAll('button,a')].find(e=>e.textContent.trim()===text);if(!el)throw new Error('Missing '+text);el.click();},text);
 await clickText('Turf'); assert.equal(await page.$$eval('.rls-card',x=>x.length),1);
 await clickText('Add to quote');
 await clickText('All materials');
 await clickText('Add to order');
 await page.goto('http://127.0.0.1:5188/landscaper-supply/cart',{waitUntil:'networkidle2'});
 assert.equal(await page.$$eval('.rls-line',x=>x.length),2);
 await clickText('Save material list');
 await clickText('Reload saved materials at current prices');
 await page.waitForFunction(()=>[...document.querySelectorAll('.rls-line input')].every(i=>i.value==='2'));
 await clickText('Request a quote'); await page.waitForSelector('form');
 assert.match(await page.evaluate(()=>document.body.innerText),/Turf Daddy/);
 await page.screenshot({path:'artifacts/rls/quote.png',fullPage:true});
 await page.goto('http://127.0.0.1:5188/landscaper-supply/checkout',{waitUntil:'networkidle2'});
 assert.match(await page.evaluate(()=>document.body.innerText),/Simon's Gold/);
 await page.screenshot({path:'artifacts/rls/checkout.png',fullPage:true});
 const blocked=await page.evaluate(async()=>{const r=await fetch('/api/checkout/create-session',{method:'POST',headers:{'Content-Type':'application/json'},body:'{}'});return r.status}); assert.equal(blocked,403);
 await page.goto('http://127.0.0.1:5188/landscaper-supply',{waitUntil:'networkidle2'});
 await page.setViewport({width:375,height:812});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 const phones=await page.$$eval('.rls a[href^="tel:"]',a=>a.map(x=>x.getAttribute('href'))); assert(phones.every(p=>p==='tel:+16232633386'));
 await page.setRequestInterception(true); page.on('request',r=>r.url().includes('/api/public/products')?r.respond({status:503,contentType:'application/json',body:'{}'}):r.continue());
 await page.reload({waitUntil:'networkidle2'});await page.waitForFunction(()=>document.body.innerText.includes('Current catalog unavailable'));
 assert.equal(await page.$$eval('.rls-card',x=>x.length),0);
 assert.deepEqual(errors,[]);
 console.log('PASS: live catalog, photos, 375/390px layout, filters, pay/quote cart, saved-list repricing, quote and checkout handoffs, canonical phone, write protection, catalog failure.');
} finally {await browser.close()}
